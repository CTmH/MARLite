"""TrajectoryDataset — samples variable-length trajectories from an episode buffer.

Attribute classification metadata (storage type, collation type) lives in
:mod:`marlite.rollout.attribute_spec` — the single source of truth.  The
module-level lists below are derived from ``ATTR_REGISTRY`` so the two
modules stay consistent.
"""

import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader

from marlite.rollout.attribute_spec import (
    ATTR_REGISTRY,
    StorageType,
    CollateType,
    PADDING_ATTRS,
    SSL_ATTRS,
    ALL_ATTRS,
    get_as_is_attrs,
    get_dict_attrs,
    get_numeric_attrs,
    get_dynamic_attrs,
    get_obj_attrs,
)

# ===================================================================
# Attribute lists — derived from ATTR_REGISTRY at import time
# ===================================================================

# Attributes stored as raw arrays per timestep (no conversion needed)
ARRAY_ATTR = get_as_is_attrs(ALL_ATTRS)

# Attributes stored as per-agent dicts (converted via np.stack)
DICT_ATTR = get_dict_attrs(ALL_ATTRS)

# Attributes generated by TrajectoryDataset at query time
PADDING_ATTR = list(PADDING_ATTRS)

# --- Collation lists (used by trajectory_collate_fn as supersets) ---

# Numeric attributes → torch.tensor
NUMERIC_ATTR = (
    get_numeric_attrs(ALL_ATTRS)
    + list(PADDING_ATTRS)
    + list(SSL_ATTRS)
)

# Variable-length attributes → kept as Python list
DYNAMIC_LEN_ATTR = get_dynamic_attrs(ALL_ATTRS)

# Object-type attributes → gym.Space or mixed, preserved as-is
OBJ_ATTR = get_obj_attrs(ALL_ATTRS)


# ===================================================================
# TrajectoryDataset
# ===================================================================

class TrajectoryDataset(Dataset):

    def __init__(
        self, sample_id_list, episode_buffer, traj_len,
        required_attrs=None,
    ):
        """Create a trajectory dataset.

        Parameters
        ----------
        sample_id_list : list
            List of (episode_id, position) tuples.
        episode_buffer : dict
            Mapping from episode_id to episode dict.
        traj_len : int
            Desired trajectory length.
        required_attrs : None, str, or list[str], optional
            Attribute profile.  ``None`` means full profile (all registered
            attrs).  A string looks up a named profile (e.g. ``"qmix"``).
            A list specifies explicit attribute names.
        """
        self.sample_id_list = sample_id_list
        self.episode_buffer = episode_buffer
        self.traj_len = traj_len
        self.padding_attr = PADDING_ATTR

        if required_attrs is None:
            self.array_attr = ARRAY_ATTR
            self.dict_attr = DICT_ATTR
        else:
            # Only include attributes that are (a) in the full registered
            # classification and (b) requested by the profile.
            attrs_set = set(required_attrs)
            self.array_attr = [a for a in ARRAY_ATTR if a in attrs_set]
            self.dict_attr = [a for a in DICT_ATTR if a in attrs_set]

    def __len__(self):
        return len(self.sample_id_list)

    def __getitem__(self, idx):
        episode_id, pos = self.sample_id_list[idx]
        sample = {
            key: [] for key in self.array_attr + self.dict_attr + self.padding_attr
        }
        start = pos - self.traj_len + 1

        # Pad with zeros / empty dicts when not enough history precedes *pos*
        while start < 0:
            for key in self.array_attr:
                sample[key].append(
                    np.zeros_like(self.episode_buffer[episode_id][key][0])
                )

            for key in self.dict_attr:
                first_element = self.episode_buffer[episode_id][key][0]
                zero_element = np.stack(
                    [np.zeros_like(value) for value in first_element.values()]
                )
                sample[key].append(zero_element)

            for key in self.padding_attr:
                sample[key].append(True)
            start += 1

        # Array-type attributes — no conversion needed
        for key in self.array_attr:
            sample[key] += self.episode_buffer[episode_id][key][start : pos + 1]

        # Dictionary-type attributes — convert each dict to (N, …) numpy array
        for key in self.dict_attr:
            dict_sequence = self.episode_buffer[episode_id][key][start : pos + 1]
            converted_sequence = []
            for dict_item in dict_sequence:
                converted_array = np.stack(
                    list(dict_item.values()), axis=0
                )
                converted_sequence.append(converted_array)
            sample[key] += converted_sequence

        for key in self.padding_attr:
            sample[key] += [False] * (pos - start + 1)

        return sample

    def __iter__(self):
        for i in range(len(self)):
            yield self[i]


