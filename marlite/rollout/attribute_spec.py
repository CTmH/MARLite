# ---------------------------------------------------------------------------
# Resolution
# ---------------------------------------------------------------------------

def resolve_required_attrs(
    required_attrs: Union[None, str, List[str], tuple] = None,
) -> List[str]:
    """Normalize *required_attrs* to a flat list of attribute names.

    ``None``
        Returns the **full** profile (all registered attrs) for backward
        compatibility — existing code that does not specify ``required_attrs``
        will collect and process everything exactly as before.

    ``str``
        Looks up the named profile in ``ROLLOUT_PROFILES``.

    ``list[str]`` / ``tuple``
        Validates that every name appears in ``ATTR_REGISTRY`` and returns
        the list unchanged.
    """
    if required_attrs is None:
        return ROLLOUT_PROFILES["full"]

    if isinstance(required_attrs, str):
        if required_attrs not in ROLLOUT_PROFILES:
            raise ValueError(
                f"Unknown rollout profile '{required_attrs}'. "
                f"Available: {list(ROLLOUT_PROFILES.keys())}"
            )
        return ROLLOUT_PROFILES[required_attrs]

    if isinstance(required_attrs, (list, tuple)):
        for attr in required_attrs:
            if attr not in ATTR_REGISTRY:
                raise ValueError(
                    f"Unknown attribute '{attr}' in required_attrs list. "
                    f"Known attributes: {list(ATTR_REGISTRY.keys())}"
                )
        return list(required_attrs)

    raise TypeError(
        f"required_attrs must be None, str, list, or tuple, got {type(required_attrs)}"
    )


# ---------------------------------------------------------------------------
# Filter helpers — used by both rollout and TrajectoryDataset
# ---------------------------------------------------------------------------

def get_timestep_attrs(required_attrs: List[str]) -> List[str]:
    """Return only the per-timestep attributes from *required_attrs*.

    Filters out episode-level and padding attributes.
    """
    return [
        a for a in required_attrs
        if ATTR_REGISTRY[a]["storage"] in (StorageType.AS_IS, StorageType.DICT)
    ]


def get_as_is_attrs(required_attrs: List[str]) -> List[str]:
    """Return AS_IS-type attributes from *required_attrs*."""
    return [
        a for a in required_attrs
        if (ATTR_REGISTRY[a]["storage"] == StorageType.AS_IS
            and ATTR_REGISTRY[a].get("collate") != CollateType.SKIP)
    ]


def get_dict_attrs(required_attrs: List[str]) -> List[str]:
    """Return DICT-type attributes from *required_attrs*."""
    return [
        a for a in required_attrs
        if (ATTR_REGISTRY[a]["storage"] == StorageType.DICT
            and ATTR_REGISTRY[a].get("collate") != CollateType.SKIP)
    ]


def get_numeric_attrs(required_attrs: List[str]) -> List[str]:
    """Return attributes whose collate type is NUMERIC."""
    return [
        a for a in required_attrs
        if ATTR_REGISTRY[a].get("collate") == CollateType.NUMERIC
    ]


def get_dynamic_attrs(required_attrs: List[str]) -> List[str]:
    """Return attributes whose collate type is DYNAMIC (variable-length)."""
    return [
        a for a in required_attrs
        if ATTR_REGISTRY[a].get("collate") == CollateType.DYNAMIC
    ]


def get_obj_attrs(required_attrs: List[str]) -> List[str]:
    """Return attributes whose collate type is OBJ (gym.Space / mixed)."""
    return [
        a for a in required_attrs
        if ATTR_REGISTRY[a].get("collate") == CollateType.OBJ
    ]


