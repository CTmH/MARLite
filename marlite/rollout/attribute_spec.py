"""Attribute specification and registry for rollout data collection.

Defines which attributes are collected during rollout episodes, their
storage types (for ``TrajectoryDataset`` processing), collation types
(for ``trajectory_collate_fn``), and per-algorithm profiles that select
the appropriate set of attributes.

This module is the single source of truth for attribute metadata.
:mod:`marlite.util.trajectory_dataset` derives its processing lists
from ``ATTR_REGISTRY`` so the two modules stay consistent.
"""

from enum import Enum
from typing import Dict, FrozenSet, List, Optional, Set, Union


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class StorageType(Enum):
    """How the attribute is stored in the raw episode buffer."""
    AS_IS = "as_is"        # Stored as-is (numpy arrays per timestep)
    DICT = "dict"          # Stored as per-agent dicts, converted via np.stack
    EPISODE = "episode"    # Scalar per episode (not per timestep)
    PADDING = "padding"    # Generated by TrajectoryDataset, not from rollout


class CollateType(Enum):
    """How the attribute is handled by ``trajectory_collate_fn``."""
    NUMERIC = "numeric"    # → torch.tensor
    DYNAMIC = "dynamic"    # variable-length → kept as Python list
    OBJ = "obj"            # gym.Space or mixed-type → preserved / special handling
    SKIP = "skip"          # Not processed by the dataset at all


